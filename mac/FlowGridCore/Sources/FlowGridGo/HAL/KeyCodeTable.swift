import CoreGraphics
import Foundation
import FlowGridCore

/// macOS 虚拟键码（NSEvent.keyCode / CGKeyCode）↔ USB HID Usage ID（协议 §6.1）。
/// 采用 US 布局；其他布局的字符差异由系统层处理（MVP 约定，见 README）。
public enum KeyCodeTable {

    /// (macOS 虚拟键码, HID Usage ID)
    private static let pairs: [(CGKeyCode, UInt16)] = [
        // 字母 A-Z
        (0x00, 0x04), (0x0B, 0x05), (0x08, 0x06), (0x02, 0x07), (0x0E, 0x08),
        (0x03, 0x09), (0x05, 0x0A), (0x04, 0x0B), (0x22, 0x0C), (0x26, 0x0D),
        (0x28, 0x0E), (0x25, 0x0F), (0x2E, 0x10), (0x1F, 0x11), (0x23, 0x12),
        (0x0C, 0x13), (0x0D, 0x14), (0x01, 0x15), (0x11, 0x16), (0x20, 0x17),
        (0x09, 0x18), (0x0F, 0x19), (0x07, 0x1A), (0x10, 0x1B), (0x06, 0x1C),
        (0x2D, 0x1D),
        // 数字行 1-0
        (0x12, 0x1E), (0x13, 0x1F), (0x14, 0x20), (0x15, 0x21), (0x17, 0x22),
        (0x16, 0x23), (0x1A, 0x24), (0x1C, 0x25), (0x19, 0x26), (0x1D, 0x27),
        // 符号与编辑键
        (0x24, 0x28), // Return
        (0x35, 0x29), // Escape
        (0x33, 0x2A), // Delete (Backspace)
        (0x30, 0x2B), // Tab
        (0x31, 0x2C), // Space
        (0x1B, 0x2D), (0x18, 0x2E), (0x21, 0x2F), (0x1E, 0x30), (0x2A, 0x31),
        (0x29, 0x33), (0x27, 0x34), (0x32, 0x35), (0x2B, 0x36), (0x2F, 0x37),
        (0x2C, 0x38),
        (0x39, 0x39), // Caps Lock
        (0x7A, 0x3A), (0x78, 0x3B), (0x63, 0x3C), (0x76, 0x3D), (0x60, 0x3E),
        (0x61, 0x3F), (0x62, 0x40), (0x64, 0x41), (0x65, 0x42), (0x6D, 0x43),
        (0x67, 0x44), (0x6F, 0x45), // F1-F12
        // 导航
        (0x72, 0x49), // Help → Insert
        (0x73, 0x4A), // Home
        (0x74, 0x4B), // PageUp
        (0x75, 0x4C), // Forward Delete
        (0x77, 0x4D), // End
        (0x79, 0x4E), // PageDown
        (0x7C, 0x4F), // Right
        (0x7B, 0x50), // Left
        (0x7D, 0x51), // Down
        (0x7E, 0x52), // Up
        // 小键盘
        (0x41, 0x63), // Keypad .
        (0x43, 0x55), // Keypad *
        (0x45, 0x57), // Keypad +
        (0x47, 0x53), // Keypad Clear
        (0x4B, 0x54), // Keypad /
        (0x4C, 0x58), // Keypad Enter
        (0x4E, 0x56), // Keypad -
        (0x51, 0x67), // Keypad =
        (0x52, 0x62), (0x53, 0x59), (0x54, 0x5A), (0x55, 0x5B), (0x56, 0x5C),
        (0x57, 0x5D), (0x58, 0x5E), (0x59, 0x5F), (0x5B, 0x60), (0x5C, 0x61),
        // 修饰键（左右）
        (0x3B, 0xE0), (0x38, 0xE1), (0x3A, 0xE2), (0x37, 0xE3),
        (0x3E, 0xE4), (0x3C, 0xE5), (0x3D, 0xE6), (0x36, 0xE7),
    ]

    private static let vkToHIDMap: [CGKeyCode: UInt16] = Dictionary(
        pairs.map { ($0.0, $0.1) }, uniquingKeysWith: { first, _ in first }
    )

    private static let hidToVKMap: [UInt16: CGKeyCode] = Dictionary(
        pairs.map { ($0.1, $0.0) }, uniquingKeysWith: { first, _ in first }
    )

    public static func hidUsage(forVirtualKey keyCode: CGKeyCode) -> UInt16? {
        vkToHIDMap[keyCode]
    }

    public static func virtualKey(forHID usage: UInt16) -> CGKeyCode? {
        hidToVKMap[usage]
    }

    // MARK: - 修饰键掩码（协议 §6.2）↔ CGEventFlags

    public static func modifierMask(from flags: CGEventFlags) -> UInt8 {
        var mask: UInt8 = 0
        if flags.contains(.maskControl) { mask |= FGModifier.leftCtrl }
        if flags.contains(.maskShift) { mask |= FGModifier.leftShift }
        if flags.contains(.maskAlternate) { mask |= FGModifier.leftAlt }
        if flags.contains(.maskCommand) { mask |= FGModifier.leftMeta }
        return mask
    }

    public static func flags(fromModifiers mask: UInt8) -> CGEventFlags {
        var flags: CGEventFlags = []
        if mask & FGModifier.ctrl != 0 { flags.insert(.maskControl) }
        if mask & FGModifier.shift != 0 { flags.insert(.maskShift) }
        if mask & FGModifier.alt != 0 { flags.insert(.maskAlternate) }
        if mask & FGModifier.meta != 0 { flags.insert(.maskCommand) }
        return flags
    }
}
